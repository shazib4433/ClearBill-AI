def seed_databases(
    his_db_path: Path | None = None,
    audit_db_path: Path | None = None,
    reset_audit: bool = False,
) -> tuple[int, int]:
    """Create and seed mock_his.db and initialize clearbill_audit.db with immutability triggers."""
    his_path = his_db_path or Path(os.getenv("HIS_DB_PATH", str(ROOT_DIR / "database" / "mock_his.db")))
    audit_path = audit_db_path or Path(os.getenv("AUDIT_DB_PATH", str(ROOT_DIR / "database" / "clearbill_audit.db")))
    his_path.parent.mkdir(parents=True, exist_ok=True)
    audit_path.parent.mkdir(parents=True, exist_ok=True)

    # Recreate Read-Only Mock HIS DB cleanly so seeding is deterministic and idempotent
    if his_path.exists():
        his_path.unlink()

    his_engine = create_engine(f"sqlite:///{his_path}", future=True)
    HISBase.metadata.create_all(bind=his_engine)

    employees = _employees_data()
    cases = _build_demo_cases()

    with Session(his_engine) as session:
        session.add_all(employees)
        for case in cases:
            session.add(case["patient"])
            session.add(case["admission"])
            session.add_all(case["ledger"])
            session.add_all(case["orders"])
            session.add_all(case["notes"])
            session.add_all(case["nursing"])
            session.add_all(case["labs"])
        session.commit()
    his_engine.dispose()

    # Initialize ClearBill Audit/Staging DB (preserve existing logs unless --reset-audit)
    if reset_audit and audit_path.exists():
        audit_path.unlink()

    audit_engine = create_engine(f"sqlite:///{audit_path}", future=True)
    AuditBase.metadata.create_all(bind=audit_engine)
    create_audit_immutability_triggers(audit_engine)
    audit_engine.dispose()

    return len(employees), len(cases)


def main() -> None:
    parser = argparse.ArgumentParser(description="Seed ClearBill AI Mock HIS and Audit SQLite databases.")
    parser.add_argument(
        "--reset-audit",
        action="store_true",
        help="Also recreate clearbill_audit.db (wiping existing staging sessions & audit logs).",
    )
    args = parser.parse_args()
    emp_count, patient_count = seed_databases(reset_audit=args.reset_audit)
    print(
        f"Seeded Mock HIS DB with {emp_count} authorized employees and {patient_count} inpatient UHID cases; "
        f"initialized Audit DB with SQLite immutability triggers."
    )


if __name__ == "__main__":
    main()
